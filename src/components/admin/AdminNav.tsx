export function AdminNav() {
  const pathname = usePathname();

  // For active matching — /admin/products/new and /admin/products/[id] should all highlight Products
  const isActive = (href: string) => {
    if (href === '/admin') return pathname === '/admin';
    return pathname.startsWith(href);
  };

  return (
    <nav className="admin-nav" aria-label="Admin navigation">
      <div className="admin-nav-brand">
        <span className="admin-title">Kamran Cloth House</span>
        <span className="admin-title-sub">Admin Panel</span>
      </div>

      <ul className="admin-links" role="list">
        {NAV_LINKS.map((link) => (
          <li key={link.href}>
            <Link
              href={link.href}
              className="admin-link"
              aria-current={isActive(link.href) ? 'page' : undefined}
            >
              {link.icon}
              {link.label}
            </Link>
          </li>
        ))}
      </ul>

      <div className="admin-nav-footer">
        <SignOutButton />
      </div>
    </nav>
  );
}
